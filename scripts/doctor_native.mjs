#!/usr/bin/env node
/** Offline native development-build preflight. It never creates credentials,
 * probes private networks, uploads code, or pretends to verify audio/video.
 * Use --strict for a physical-device readiness gate, --api <url> to inspect
 * the non-secret EXPO_PUBLIC_TUTTT_API_URL without writing it to a file.
 */
import {existsSync,readFileSync,readdirSync} from 'node:fs';
import {createRequire} from 'node:module';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {isIP} from 'node:net';
import {inspectNpmLock,inspectInstalledTree} from './native_dependency_integrity.mjs';

const projectRoot=resolve(fileURLToPath(new URL('../',import.meta.url)));
const readJson=file=>JSON.parse(readFileSync(file,'utf8'));
const require=createRequire(import.meta.url);
export function mobileSourcePaths(folder,relative=''){
 return readdirSync(folder,{withFileTypes:true}).flatMap(item=>{
  const next=join(relative,item.name),full=join(folder,item.name);
  if(item.isDirectory())return mobileSourcePaths(full,next);
  return item.isFile()&&/\.(ts|tsx)$/.test(item.name)?[next]:[];
 });
}
const check=(id,status,message)=>({id,status,message});
export function assessApiUrl(raw){
 if(!raw?.trim())return check('api-url','WARN','Chưa đặt EXPO_PUBLIC_TUTTT_API_URL (không có API để thử trên điện thoại)');
 let url;
 try{url=new URL(raw);}catch{return check('api-url','FAIL','Địa chỉ API không hợp lệ');}
 if(!['http:','https:'].includes(url.protocol)||url.username||url.password||url.search||url.hash||!url.hostname)
  return check('api-url','FAIL','API phải là HTTP(S) gốc, không chứa thông tin đăng nhập, query hoặc fragment');
 if(url.pathname!=='/'&&url.pathname!=='')return check('api-url','FAIL','API phải là origin, không kèm /api hoặc đường dẫn');
 if(/(^|\.)(example\.(com|org|net)|invalid|test)$/.test(url.hostname.toLowerCase()))return check('api-url','FAIL','Đây là tên miền mẫu, không phải API thật');
 const hostname=url.hostname.toLowerCase().replace(/^\[|\]$/g,'');
 if(hostname==='localhost'||hostname==='127.0.0.1'||hostname==='::1'||hostname==='0.0.0.0')
  return check('api-url','FAIL','localhost/loopback không truy cập được từ điện thoại vật lý; dùng IP LAN hoặc HTTPS staging');
 if(url.protocol==='http:'){
  const parts=hostname.split('.').map(Number);
  const privateV4=isIP(hostname)===4&&
   (parts[0]===10||(parts[0]===172&&parts[1]>=16&&parts[1]<=31)||(parts[0]===192&&parts[1]===168));
  return privateV4?check('api-url','WARN','API HTTP trên mạng LAN: cần xác minh Android cleartext / iOS ATS và quyền firewall trên thiết bị'):
   check('api-url','FAIL','HTTP công khai không phù hợp với phiên có token; dùng HTTPS');
 }
 return check('api-url','PASS','Có origin API HTTPS (chưa xác thực khả năng truy cập từ điện thoại)');
}
/** Expo SDK 58 officially pairs RN 0.88 with React 19.3 and requires Node >=22.13.
 * This is a DECLARATION check; it is not a substitute for resolving npm peers. */
export function assessRuntimeMatrix({dependencies={},nodeVersion=process.versions.node}){
 const checks=[];
 for(const [name,expected] of [['expo','58'],['react','19.3'],['react-native','0.88']]){
  const actual=dependencies[name]||'';
  const aligned=new RegExp('^[\\^~]?'+expected.replaceAll('.','\\.')+'(?:\\.|$)').test(actual);
  checks.push(check('sdk:'+name,aligned?'PASS':'FAIL',aligned?`${name} ${actual} khớp Expo SDK 58`: `${name} ${actual||'(thiếu)'} không khớp Expo SDK 58 (${expected}.x)`));
 }
 const parts=String(nodeVersion).replace(/^v/,'').split('.').map(Number);
 const compatible=parts.length>=2&&Number.isInteger(parts[0])&&Number.isInteger(parts[1])&&(parts[0]>22||(parts[0]===22&&parts[1]>=13));
 checks.push(check('node-runtime',compatible?'PASS':'FAIL',compatible?`Node ${nodeVersion} đáp ứng SDK 58`:`Node ${nodeVersion} chưa đáp ứng SDK 58 (yêu cầu >=22.13.0)`));
 return checks;
}
/** Resolve visible peer-pair pitfalls without pretending to run npm's peer resolver.
 * A green declaration is only a precondition; npm ci --strict-peer-deps is authoritative. */
export function assessReactPins({dependencies={},overrides={}}={}){
 const react=dependencies.react;
 const dom=dependencies['react-dom'];
 const rsc=overrides['react-server-dom-webpack'];
 return [
  check('peer:react-dom',react&&dom===react?'PASS':'FAIL',
   react&&dom===react?`react-dom và react được ghim cùng bản ${react}`:'react và react-dom phải ghim đúng cùng phiên bản để tránh ERESOLVE'),
  check('peer:react-server-dom-webpack',react&&rsc===react?'PASS':'FAIL',
   react&&rsc===react?`react-server-dom-webpack override ghim ${react}`:'Thiếu override react-server-dom-webpack cùng bản react (peer conflict Expo/LiveKit SDK 58)'),
 ];
}
/** Lockfiles are generated by npm from the registry and must not be fabricated. */
export function assessLockIntegrity(lock,packageJson){
 if(!lock)return check('lock-integrity','WARN','Chưa có lockfile hợp lệ; cần npm install --strict-peer-deps trên máy có registry');
 const root=lock.packages?.[''];
 if(!root||lock.lockfileVersion<3||root.name!==packageJson?.name||root.version!==packageJson?.version)
  return check('lock-integrity','FAIL','package-lock.json không khớp package.json hoặc không thuộc lockfile npm v3');
 for(const area of ['dependencies','devDependencies']){
  for(const [key,value] of Object.entries(packageJson[area]||{})){
   if(root[area]?.[key]!==value)return check('lock-integrity','FAIL',`Lockfile chưa phản ánh ${area}.${key}; tạo lại bằng npm install`);
  }
 }
 return check('lock-integrity','PASS','Lockfile root khớp khai báo (chưa xác nhận npm ci và peer resolution)');
}
/** React Native 0.88 removed these properties from strict public types. */
export function assessSdk58Source(source){
 const invalid=[];
 if(/<StatusBar\b[^>]*\b(?:backgroundColor|translucent|networkActivityIndicatorVisible)(?=\s|=|\/?>)/.test(source))invalid.push('StatusBar legacy props');
 if(/<Modal\b[^>]*\banimated(?=\s|=|\/?>)/.test(source))invalid.push('Modal animated prop');
 if(/\bInteractionManager\b/.test(source))invalid.push('removed InteractionManager');
 if(/from ['"]react-native\/Libraries\//.test(source))invalid.push('react-native/Libraries deep import');
 return check('sdk58-source',invalid.length?'FAIL':'PASS',invalid.length?`API không phù hợp RN 0.88: ${invalid.join(', ')}`:'Không thấy API React Native bị xóa trong các nguồn đã quét');
}
export function assessNativeConfig({app,packageJson,rootPackage,eas,apiUrl,dependenciesInstalled=false,lockfilePresent=true,nodeVersion=process.versions.node}){
 const checks=[];
 const p=app?.expo||{};
 const scripts=packageJson?.scripts||{};
 checks.push(check('versions',p.version===rootPackage?.version&&p.version===packageJson?.version?'PASS':'FAIL',
  p.version===rootPackage?.version&&p.version===packageJson?.version?'Phiên bản web/mobile đã đồng bộ':'Phiên bản root, mobile hoặc app.json chưa đồng bộ'));
 checks.push(...assessRuntimeMatrix({dependencies:packageJson?.dependencies,nodeVersion}));
 checks.push(...assessReactPins({dependencies:packageJson?.dependencies,overrides:packageJson?.overrides}));
 const doctorVersion=packageJson?.devDependencies?.['expo-doctor']||'';
 checks.push(check('doctor-local',/^\d+\.\d+\.\d+$/.test(doctorVersion)&&scripts.doctor==='expo-doctor'?'PASS':'FAIL',
   /^\d+\.\d+\.\d+$/.test(doctorVersion)&&scripts.doctor==='expo-doctor'?`Expo Doctor ${doctorVersion} ghim trong devDependencies`:'expo-doctor phải được ghim trong devDependencies và gọi qua npm run doctor'));
 const plugins=p.plugins||[];
 for(const plugin of ['@livekit/react-native-expo-plugin','@config-plugins/react-native-webrtc'])
  checks.push(check(`plugin:${plugin}`,plugins.includes(plugin)&&!!packageJson?.dependencies?.[plugin]?'PASS':'FAIL',
   plugins.includes(plugin)&&!!packageJson?.dependencies?.[plugin]?`Đã khai báo ${plugin}`:`Thiếu plugin/phiên bản ${plugin}`));
 for(const platform of ['android','ios']){
  const id=platform==='android'?p.android?.package:p.ios?.bundleIdentifier;
  checks.push(check(`${platform}-id`,!id?'FAIL':id.startsWith('com.example.')?'WARN':'PASS',
   !id?`Thiếu ${platform} application identifier`:id.startsWith('com.example.')?`${platform} đang dùng ID minh họa; phải đổi sang ID sở hữu trước khi ký build`:`${platform} đã đặt application identifier`));
 }
 for(const permission of ['android.permission.RECORD_AUDIO','android.permission.CAMERA'])
  checks.push(check('permission:'+permission,p.android?.permissions?.includes(permission)?'PASS':'FAIL',
   p.android?.permissions?.includes(permission)?`Android khai báo ${permission}`:`Android thiếu ${permission}`));
 for(const permission of ['NSCameraUsageDescription','NSMicrophoneUsageDescription'])
  checks.push(check('ios-privacy:'+permission,p.ios?.infoPlist?.[permission]?.trim()?'PASS':'FAIL',
   p.ios?.infoPlist?.[permission]?.trim()?`iOS khai báo ${permission}`:`iOS thiếu ${permission}`));
 checks.push(check('dev-client',!!packageJson?.dependencies?.['expo-dev-client']&&!!scripts.start?.includes('--dev-client')?'PASS':'FAIL',
  !!packageJson?.dependencies?.['expo-dev-client']&&!!scripts.start?.includes('--dev-client')?'Có development client (không dùng Expo Go cho WebRTC)':'Thiếu dev client hoặc lệnh khởi động dev client'));
 checks.push(check('eas-profile',!!eas?.build?.development?.developmentClient&&eas?.build?.development?.distribution==='internal'?'PASS':'FAIL',
  !!eas?.build?.development?.developmentClient&&eas?.build?.development?.distribution==='internal'?'Đã cấu hình build nội bộ cho development client':'Thiếu EAS development build profile'));
 checks.push(check('lockfile',lockfilePresent?'PASS':'WARN',lockfilePresent?'Có package-lock.json mobile để cố định dependency tree':'Chưa có mobile/package-lock.json: build giữa các máy chưa tái lập được; tạo bằng npm install sau khi giải quyết dependency'));
 checks.push(check('dependencies',dependenciesInstalled?'PASS':'WARN',
  dependenciesInstalled?'Có node_modules trên máy kiểm tra (chưa thay thế expo-doctor/typecheck)':'Chưa cài node_modules mobile: cần npm install, expo-doctor và tsc trên máy phát triển'));
 checks.push(assessApiUrl(apiUrl));
 return checks;
}
export function inspectNativeProject({root=projectRoot,apiUrl=process.env.EXPO_PUBLIC_TUTTT_API_URL||''}={}){
 const mobile=join(root,'mobile');
 const mobilePackage=readJson(join(mobile,'package.json'));
 const appJson=readJson(join(mobile,'app.json'));
 const appConfig=require(join(mobile,'app.config.js'));
 const effectiveExpo=appConfig({config:appJson.expo});
 const effectiveApp={expo:effectiveExpo};
 const checks=assessNativeConfig({app:effectiveApp,packageJson:mobilePackage,
  rootPackage:readJson(join(root,'package.json')),eas:readJson(join(mobile,'eas.json')),
  apiUrl,dependenciesInstalled:existsSync(join(mobile,'node_modules','expo','package.json')),
  lockfilePresent:existsSync(join(mobile,'package-lock.json'))});
 const lockPath=join(mobile,'package-lock.json');
 if(existsSync(lockPath)){
  try{checks.push(assessLockIntegrity(readJson(lockPath),mobilePackage));}
  catch{checks.push(check('lock-integrity','FAIL','package-lock.json không phải JSON hợp lệ'));}
 }else checks.push(assessLockIntegrity(null,mobilePackage));
 let fullLock=null;
 if(existsSync(lockPath)){try{fullLock=readJson(lockPath);}catch{/* lock-integrity above reports corrupt JSON */}}
 const resolvedCheck=inspectNpmLock(fullLock,mobilePackage);
 checks.push(check('resolved-lock',resolvedCheck.status==='BLOCKED'?'WARN':resolvedCheck.status,resolvedCheck.detail));
 const treeCheck=inspectInstalledTree(mobilePackage,mobile);
 checks.push(check('installed-tree',treeCheck.status==='BLOCKED'?'WARN':treeCheck.status,treeCheck.detail));
 for(const path of ['App.tsx',...mobileSourcePaths(join(mobile,'src'),'src')]){
  checks.push({...assessSdk58Source(readFileSync(join(mobile,path),'utf8')),id:'sdk58-source:'+path});
 }
 return {version:readJson(join(root,'package.json')).version,
  status:checks.some(x=>x.status==='FAIL')?'FAIL':checks.some(x=>x.status==='WARN')?'WARN':'PASS',
  checks,limitations:['Không chạy npm peer resolution hoặc TypeScript semantic check','Không tạo native build','Không kiểm tra tài khoản Apple/Expo/Android signing','Không kiểm tra SFU, âm thanh, camera hoặc kết nối hai thiết bị']};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const pos=process.argv.indexOf('--api');const strict=process.argv.includes('--strict');
 try{
  const report=inspectNativeProject({apiUrl:pos<0?process.env.EXPO_PUBLIC_TUTTT_API_URL||'':process.argv[pos+1]||''});
  if(process.argv.includes('--json'))console.log(JSON.stringify(report,null,2));
  else{for(const item of report.checks)console.log(`${item.status} ${item.id}: ${item.message}`);
   console.log('Giới hạn: '+report.limitations.join('; '));}
  if(report.status==='FAIL'||(strict&&report.status==='WARN'))process.exitCode=1;
 }catch(error){console.error('FAIL native preflight:',error instanceof Error?error.message:'Cấu hình không hợp lệ');process.exitCode=1;}
}
