test('viewer counter lists authenticated room presence without requiring LiveKit or microphone',async()=>{
 const host=await request('/api/session','POST',{name:'Chủ phòng'});
 const silent=await request('/api/session','POST',{name:'Người nghe'});
 const late=await request('/api/session','POST',{name:'Khách ngoài'});
 const created=await request('/api/rooms','POST',{title:'Danh sách người xem',tag:'Tâm sự',type:'voice'},host.cookie);
 const id=created.data.room.id,route=`/api/rooms/${id}/audience`;
 assert.equal((await request(route,'GET',null,silent.cookie)).status,403,'outsiders cannot enumerate viewer names');
 assert.equal((await request(route)).status,401,'anonymous cannot enumerate viewer names');
 await request(`/api/rooms/${id}/join`,'POST',null,host.cookie);
 await request(`/api/rooms/${id}/join`,'POST',null,silent.cookie);
 let result=await request(route,'GET',null,host.cookie);
 assert.equal(result.status,200);
 assert.equal(result.data.count,2);
 assert.deepEqual(result.data.members.map(m=>m.name),['Chủ phòng','Người nghe']);
 assert.deepEqual(result.data.members.map(m=>m.role),['host','viewer']);
 assert.equal(result.data.members[1].onStage,false,'viewer does not need Voice/LiveKit');
 assert.ok(!JSON.stringify(result.data).includes('token'),'session credentials never appear in audience');
 await request(`/api/me`,'PATCH',{name:'Người xem mới'},silent.cookie);
 result=await request(route,'GET',null,host.cookie);
 assert.equal(result.data.members[1].name,'Người xem mới');
 await request(`/api/rooms/${id}/leave`,'POST',null,silent.cookie);
 result=await request(route,'GET',null,host.cookie);
 assert.equal(result.data.count,1);
 assert.equal((await request(route,'GET',null,late.cookie)).status,403);
 assert.equal((await request(route,'GET',null,silent.cookie)).status,403);
});
